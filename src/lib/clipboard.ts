/**
 * `navigator.clipboard` needs a secure context and can reject on a denied permission, so this
 * always falls back to the old hidden-textarea + execCommand('copy') trick rather than leaving
 * the caller with nothing. Used everywhere something gets copied in this app, so that fallback
 * isn't accidentally missing on any one of them.
 */
export async function copyToClipboard(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // Fall through to the selection-based fallback.
  }

  const textarea = document.createElement('textarea');
  textarea.value = text;
  textarea.setAttribute('readonly', '');
  textarea.style.position = 'fixed';
  textarea.style.opacity = '0';
  try {
    document.body.appendChild(textarea);
    textarea.select();
    return document.execCommand('copy');
  } catch {
    return false;
  } finally {
    textarea.remove();
  }
}
